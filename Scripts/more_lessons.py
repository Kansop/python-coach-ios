from __future__ import annotations


def check(stdout=None, contains=None, names=None, stdin=None, append=None):
    return {
        "stdin": list(stdin or []),
        "appendCode": append,
        "stdoutEquals": stdout,
        "stdoutContains": list(contains or []),
        "valueNames": list(names or []),
    }


def lesson(
    id,
    title,
    explanation,
    example_code,
    example_note,
    exercise,
    starter,
    hints,
    solution,
    tests,
    source=None,
    one_of=None,
    xp=10,
    example_stdin=None,
    kind="code",
):
    return {
        "id": id,
        "title": title,
        "explanation": explanation.strip(),
        "exampleCode": example_code.strip("\n"),
        "exampleNote": example_note.strip(),
        "exercise": exercise.strip(),
        "starterCode": starter.strip("\n"),
        "hints": hints,
        "sourceMustContain": list(source or []),
        "sourceMustContainOneOf": list(one_of or []),
        "xp": xp,
        "kind": kind,
        "quizChoices": [],
        "quizAnswer": -1,
        "quizExplain": "",
        "solution": solution.strip("\n"),
        "exampleStdin": list(example_stdin or []),
        "tests": tests,
    }


def quiz(id, title, explanation, prompt, choices, answer, explain, hints):
    return {
        "id": id,
        "title": title,
        "explanation": explanation.strip(),
        "exampleCode": 'print("Quick check")',
        "exampleNote": "No code to run here. Read the question and pick an answer.",
        "exercise": prompt.strip(),
        "starterCode": "# Choose an answer on this screen.",
        "hints": hints,
        "sourceMustContain": [],
        "sourceMustContainOneOf": [],
        "xp": 5,
        "kind": "quiz",
        "quizChoices": choices,
        "quizAnswer": answer,
        "quizExplain": explain.strip(),
        "solution": "",
        "exampleStdin": [],
        "tests": [],
    }


